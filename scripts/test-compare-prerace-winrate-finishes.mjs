import assert from 'node:assert/strict';
import {comparePreRaceWinRates} from './compare-prerace-winrate-finishes.mjs';
const racers=Array.from({length:6},(_,i)=>({boat:i+1,racerId:String(4001+i),statsVerified:true,nationalWinRate:i===3?8:i===0?3:5,localWinRate:i===3?8:i===0?3:5}));
const snapshot={verified:true,date:'20261118',venue:2,race:1,capturedAt:'2026-11-18T08:00:00+09:00',cutoffAt:'2026-11-18T12:00:00+09:00',racers};
const result={independentlyVerified:true,date:'20261118',venue:2,race:1,racers:racers.map((x,i)=>({racerId:x.racerId,boat:x.boat,finish:i===3?1:i<3?i+2:i===3?1:i+1}))};
const pair={snapshot,result};
const good=comparePreRaceWinRates([pair]);
assert.equal(good.eligibleRaces,1);
assert.equal(good.highestWinRateWins,1);
assert.equal(good.races[0].ordered[0].boat,4);
assert.equal(good.eligibleForWeightTuning,false);
const repeated=comparePreRaceWinRates([pair,pair]);
assert.equal(repeated.eligibleRaces,1);
assert.equal(repeated.rejectedRecords,1);
const duplicateRacer={...result,racers:result.racers.map((x,i)=>i===5?{...x,racerId:result.racers[4].racerId}:x)};
assert.equal(comparePreRaceWinRates([{snapshot,result:duplicateRacer}]).eligibleRaces,0);
const afterCutoff={...snapshot,capturedAt:'2026-11-18T13:00:00+09:00'};
assert.equal(comparePreRaceWinRates([{snapshot:afterCutoff,result}]).eligibleRaces,0);
const wrongDay={...snapshot,capturedAt:'2026-11-17T08:00:00+09:00'};
assert.equal(comparePreRaceWinRates([{snapshot:wrongDay,result}]).eligibleRaces,0);
const wrongCutoffDay={...snapshot,cutoffAt:'2026-11-19T12:00:00+09:00'};
assert.equal(comparePreRaceWinRates([{snapshot:wrongCutoffDay,result}]).eligibleRaces,0);
console.log('Pre-race win-rate vs finish checks passed (synthetic only)');
