import assert from 'node:assert/strict';
import {evaluateRacerScoreQuality} from './evaluate-racer-score-quality.mjs';
const racers=Array.from({length:6},(_,i)=>({boat:i+1,racerId:String(4000+i),score:100-i*10,finish:i+1}));
const race={date:'20261119',venue:2,race:3,preRaceSnapshotVerified:true,resultIndependentlyVerified:true,chronologicalHoldout:true,racers};
const perfect=evaluateRacerScoreQuality([race]);
assert.equal(perfect.eligibleRaces,1);
assert.equal(perfect.eligibleRacers,6);
assert.equal(perfect.topRatedWins,1);
assert.equal(perfect.topRatedPodiums,1);
assert.equal(perfect.topThreeRatedPodiumPlaces,3);
assert.equal(perfect.pairwiseCorrect,15);
assert.equal(perfect.meanAbsoluteRankError,0);
const reversed=evaluateRacerScoreQuality([{...race,racers:racers.map((r,i)=>({...r,finish:6-i}))}]);
assert.equal(reversed.pairwiseCorrect,0);
assert.equal(reversed.topRatedPodiums,0);
assert.equal(reversed.topThreeRatedPodiumPlaces,0);
assert.equal(evaluateRacerScoreQuality([race,race]).rejectedRaces,1);
assert.equal(evaluateRacerScoreQuality([{...race,preRaceSnapshotVerified:false}]).eligibleRaces,0);
console.log('Individual racer score quality tests passed');
