import assert from 'node:assert/strict';
import {compareExploratoryRankingModels} from './compare-exploratory-ranking-models.mjs';
const racers=Array.from({length:6},(_,i)=>({boat:i+1,racerId:String(1000+i),averageWinRate:9-i,averageST:0.10+i*0.01}));
const entries={rows:[{date:'20261118',venue:2,race:1,statsVerified:true,racers}]};
const results={rows:[{date:'20261118',venue:2,race:1,status:'parsed_needs_independent_review',racers:racers.map((r,i)=>({boat:r.boat,racerId:r.racerId,finish:i+1}))}]};
const ok=compareExploratoryRankingModels(entries,results);
assert.equal(ok.models.length,5);
assert.ok(ok.models.every(m=>m.eligibleRaces===1&&m.winnerRankOne===1&&m.winnerRankSum===1));
assert.equal(ok.eligibleForCalibration,0);
assert.equal(ok.models[0].rankingChangedFromWinrateOnly,0);
const swapped=structuredClone(results);
swapped.rows[0].racers[0].racerId='wrong';
assert.ok(compareExploratoryRankingModels(entries,swapped).models.every(m=>m.eligibleRaces===0));
const missing=structuredClone(entries);
delete missing.rows[0].racers[2].averageST;
assert.ok(compareExploratoryRankingModels(missing,results).models.every(m=>m.eligibleRaces===0));
const wrongStatus=structuredClone(results);
wrongStatus.rows[0].status='verified';
assert.ok(compareExploratoryRankingModels(entries,wrongStatus).models.every(m=>m.eligibleRaces===0));
console.log('Exploratory ranking model integrity checks passed');
