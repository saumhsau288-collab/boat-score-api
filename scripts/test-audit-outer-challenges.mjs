import assert from 'node:assert/strict';
import {auditOuterChallenges} from './audit-outer-challenges.mjs';
const boats=[70,85,90,85,50,40].map((score,i)=>({boat:i+1,course:i+1,courseVerified:true,score,averageST:0.20,exhibitionTime:6.80}));
boats[3].averageST=0.12;boats[3].exhibitionTime=6.72;
const row=actual=>({date:'20261124',venue:1,race:1,capturedBeforeCutoff:true,officialResultVerified:true,boats,actual});
const r=auditOuterChallenges([row([4,2,1]),row([2,4,1]),{...row([4,2,1]),capturedBeforeCutoff:false}]);
assert.equal(r.eligible,2);
assert.equal(r.rejected.unverified_capture_or_result,1);
assert.equal(r.flagged,2);
assert.equal(r.flaggedOuterWon,1);
assert.equal(r.flaggedWinRate,0.5);
assert.equal(r.flaggedOuterTopTwo,2);
assert.equal(r.flaggedTopTwoRate,1);
assert.equal(r.flaggedOuterTopThree,2);
assert.equal(r.flaggedTopThreeRate,1);
assert.equal(r.flaggedOuterSecond,1);
assert.equal(r.flaggedOuterThird,0);
assert.equal(r.flaggedSecondRate,0.5);
assert.equal(r.flaggedThirdRate,0);
assert.equal(r.flaggedRaces,2);
assert.equal(r.flaggedRacesWithWinner,1);
assert.equal(r.flaggedRaceWinnerRate,0.5);
assert.equal(r.flaggedRaceTopTwoRate,1);
assert.equal(r.flaggedRaceTopThreeRate,1);
assert.equal(r.flaggedRaceSecondRate,0.5);
assert.equal(r.flaggedRaceThirdRate,0);
const thirdResult=auditOuterChallenges([row([2,1,4])]);
assert.equal(thirdResult.flaggedThirdRate,1);
assert.equal(thirdResult.flaggedRaceThirdRate,1);
assert.equal(r.byScoreRelation.innerHigher.flagged,2);
assert.equal(r.byScoreRelation.innerHigher.flaggedOuterWon,1);
assert.equal(r.byScoreRelation.tie.flagged,0);
assert.equal(auditOuterChallenges([]).flaggedWinRate,null);
assert.equal(auditOuterChallenges([]).flaggedTopTwoRate,null);
assert.equal(auditOuterChallenges([]).flaggedRaceWinnerRate,null);
assert.throws(()=>auditOuterChallenges([], {minSTGap:-1}),/invalid_threshold/);
const tied=boats.map(b=>({...b,score:b.boat===3?85:b.score}));
const tieResult=auditOuterChallenges([{...row([4,2,1]),boats:tied}]);
assert.equal(tieResult.byScoreRelation.tie.flagged,1);
assert.equal(tieResult.byScoreRelation.tie.flaggedOuterWon,1);
assert.equal(tieResult.byScoreRelation.innerHigher.flagged,0);
