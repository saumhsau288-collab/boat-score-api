import assert from 'node:assert/strict';
import {auditFutureFeatureProvenance as audit} from './audit-future-feature-provenance.mjs';
const race={date:'20261122',venue:21,race:4};
const receivedAt='2026-11-22T00:30:00Z',cutoffAt='2026-11-22T01:00:00Z';
const official={...race,status:'captured_research_inputs',receivedAt,sourceUrl:'https://www.boatrace.jp/owpc/pc/race/racelist',responseSha256:'a'.repeat(64),racers:Array.from({length:6},(_,i)=>({boat:i+1,racerId:String(4001+i)}))};
const base=official.racers.map(r=>({...race,...r,verified:true,receivedAt,sourceUrl:'https://example.org/source',responseSha256:'a'.repeat(64)}));
const averageST=base.map(x=>({...x,kind:'pre_race_average_st',value:0.15}));
const makulabo=base.map(x=>({...x,scope:'same_labelled_frame_recent_up_to_50_all_venues',runs:50,firstPlaceRate:20}));
const prediction={...race,receivedAt};
const input={race,official,averageST,makulabo,prediction,cutoffAt};
const ready=audit(input);
assert.equal(ready.status,'source_evidence_ready_original_inputs_unverified');
assert.equal(ready.averageSTVerified,true);
assert.equal(ready.officialSnapshotBeforePrediction,true);
assert.equal(audit({...input,official:{...official,receivedAt:'2026-11-22T00:40:00Z'}}).officialSnapshotBeforePrediction,false);
assert.equal(audit({...input,official:{...official,sourceUrl:'https://example.org/fake'}}).status,'held');
assert.equal(ready.makulabo50Verified,true);
assert.equal(ready.eligibleForCalibration,false);
assert.equal(ready.originalInputsVerified,false);
assert.equal(audit({...input,averageST:averageST.map((x,i)=>i===2?{...x,racerId:'9999'}:x)}).averageSTVerified,false);
assert.equal(audit({...input,makulabo:makulabo.map((x,i)=>i===0?{...x,receivedAt:'2026-11-22T01:01:00Z'}:x)}).makulabo50Verified,false);
assert.equal(audit({...input,averageST:averageST.map((x,i)=>i===0?{...x,responseSha256:'bad'}:x)}).averageSTVerified,false);
assert.equal(audit({...input,prediction:{...prediction,receivedAt:'2026-11-22T00:20:00Z'}}).averageSTVerified,false);
assert.equal(audit({...input,prediction:{...prediction,receivedAt:'2026-11-22T00:20:00Z'}}).makulabo50Verified,false);
assert.equal(audit({...input,prediction:{...prediction,receivedAt:'2026-11-22T01:01:00Z'}}).status,'held');
assert.equal(audit({...input,official:{...official,race:5}}).reason,'race_identity_mismatch');
assert.equal(audit({...input,makulabo:makulabo.slice(1)}).makulabo50Verified,false);
console.log('Future pre-race source evidence cutoff, identity and missingness tests passed');
