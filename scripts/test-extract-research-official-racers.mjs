import assert from 'node:assert/strict';
import {extractOfficialRacers} from './extract-research-official-racers.mjs';
const row=(i)=>'<tr><td>'+['','１','２','３','４','５','６'][i]+'</td><td></td><td>'+(5181+i)+' / B1 選手'+i+' 埼玉/埼玉 28歳/47.0kg</td><td>F0 L0 0.14</td><td>4.17 23.33 33.33</td><td>4.52 24.10 45.78</td><td>13 30.56 44.44</td><td>43 44.62 52.31</td></tr>';
const html='<table>'+Array.from({length:6},(_,i)=>row(i+1)).join('')+'</table>';
const result=extractOfficialRacers(html);
assert.equal(result.completeSixRacers,true,JSON.stringify(result));
assert.equal(result.racers[0].racerId,'5182');
assert.equal(result.racers[0].nationalWinRate,4.17);
assert.equal(result.racers[0].localWinRate,4.52);
assert.equal(result.racers[0].motorTwoWinRate,30.56);
assert.equal(result.racers[0].averageST,0.14);
assert.equal(result.calibrationEligible,false);
assert.equal(extractOfficialRacers('<table>'+row(1)+'</table>').completeSixRacers,false);
assert.throws(()=>extractOfficialRacers(null),/html_required/);
console.log('official six-racer extraction tests passed');
