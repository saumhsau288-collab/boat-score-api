import assert from 'node:assert/strict';
import {parseOfficialResultFinishRows as parse} from './parse-official-result-finish-rows.mjs';
const heading='<tr><th>着</th><th>枠</th><th>ボートレーサー</th><th>レースタイム</th></tr>';
const fw=n=>String(n).replace(/[1-6]/g,x=>String.fromCharCode(x.charCodeAt(0)+0xfee0));
const row=(finish,boat,id)=>'<tr><td>'+fw(finish)+'</td><td>'+boat+'</td><td>'+id+' 選手名</td><td>1:50</td></tr>';
const table=rows=>'<table><tbody>'+heading+rows.join('')+'</tbody></table>';
const good=table(Array.from({length:6},(_,i)=>row(i+1,6-i,4001+i)));
assert.equal(parse(good).verified,true);
assert.deepEqual(parse(good).finishByBoat.map(v=>v.finish),[6,5,4,3,2,1]);
assert.equal(parse(good+good).reason,'ambiguous_result_tables');
assert.equal(parse(good.replace('4001 選手名','4002 選手名')).verified,false);
assert.equal(parse(good.replace('<td>６</td><td>1</td>','<td>５</td><td>1</td>')).verified,false);
assert.equal(parse('<table><tr><td>1</td></tr></table>').verified,false);
assert.equal(parse(good.replace('ボートレーサー','払戻金')).verified,false);
console.log('Official full-width result six-boat finish parser tests passed');
