import assert from 'node:assert/strict';
import {auditAllOuterPairs} from './audit-all-outer-pairs.mjs';
const boats=[90,80,70,85,65,60].map((score,i)=>({boat:i+1,course:i+1,courseVerified:true,score,averageST:0.20,exhibitionTime:6.80}));
boats[5].averageST=0.10;boats[5].exhibitionTime=6.70;
const row=actual=>({date:'20261124',venue:1,race:1,capturedBeforeCutoff:true,officialResultVerified:true,boats,actual});
const r=auditAllOuterPairs([row([6,2,1])]);
assert.equal(r.eligible,1);
assert.equal(r.flaggedRaces,1);
assert.equal(r.flaggedRacesWithWinner,1);
assert.equal(r.flaggedRaceWinnerRate,1);
assert.ok(r.examples.some(x=>x.innerCourse===4&&x.outerCourse===6));
assert.equal(r.flaggedPairsOuterWon,r.flaggedPairs);
const second=auditAllOuterPairs([row([2,6,1])]);
assert.equal(second.flaggedRacesWithSecond,1);
const third=auditAllOuterPairs([row([2,1,6])]);
assert.equal(third.flaggedRacesWithThird,1);
assert.equal(auditAllOuterPairs([]).flaggedRaceWinnerRate,null);
assert.throws(()=>auditAllOuterPairs([], {minSTGap:-1}),/invalid_threshold/);
console.log('All outer-pair synthetic assertions passed.');
