import assert from 'node:assert/strict';
import {evaluateHistoricalFirstSecond as evaluate} from './evaluate-historical-first-second.mjs';
const racers=Array.from({length:6},(_,i)=>({boat:i+1,racerId:String(4001+i),name:'R'+i,nationalWinRate:8-i,localWinRate:8-i,motorTwoWinRate:60-i*5}));
const list={status:'official_racelist_source_captured',sixRacersParsed:true,racers,date:'20261120',venue:'18',race:1};
const result={verified:true,finishByBoat:racers.map((r,i)=>({boat:r.boat,racerId:r.racerId,finish:i+1}))};
const correct=evaluate(list,result);
assert.equal(correct.status,'partial_first_second_diagnostic');
assert.equal(correct.firstCorrect,true);
assert.equal(correct.secondCorrect,true);
assert.equal(correct.orderedPairCorrect,true);
const wrong=evaluate(list,{verified:true,finishByBoat:racers.map((r,i)=>({boat:r.boat,racerId:r.racerId,finish:i===0?2:i===1?1:i+1}))});
assert.equal(wrong.firstCorrect,false);
assert.equal(wrong.secondCorrect,false);
assert.equal(wrong.orderedPairCorrect,false);
const tie=evaluate({...list,racers:racers.map((r,i)=>i===1?{...r,nationalWinRate:8,localWinRate:8,motorTwoWinRate:60}:r)},result);
assert.equal(tie.firstCorrect,null);
assert.equal(tie.orderedPairCorrect,null);
assert.equal(tie.eligibleForWeightTuning,false);
console.log('Historical first/second and ordered pair diagnostics passed');
