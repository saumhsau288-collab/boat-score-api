import assert from 'node:assert/strict';
import {auditRankFinishWithOfficial} from './audit-rank-finish-official.mjs';
const scores=Array.from({length:6},(_,i)=>({boat:i+1,score:6-i}));
const officialRows=Array.from({length:6},(_,i)=>({boat:i+1}));
const record=date=>({date,venue:2,race:1,response:{ready:true,rankedScores:scores}});
const official=date=>({date,venue:2,race:1,comparison:{rows:officialRows}});
const result=date=>({date,venue:2,race:1,verified:true,finishOrder:[1,2,3,4,5,6]});
const run=(savedRecords,officialRaces,results)=>auditRankFinishWithOfficial({savedRecords,officialRaces,results});
assert.equal(run([record('20261120')],[official('20261120')],[result('20261120')]).joinedCount,1);
assert.equal(run([record('20261121')],[official('20261120')],[result('20261120')]).joinedCount,0);
assert.equal(run([record(undefined)],[official('20261120')],[result('20261120')]).rows[0].status,'held_missing_date');
assert.equal(run([record('20261120')],[official('20261120'),official('20261120')],[result('20261120')]).joinedCount,0);
assert.equal(run([record('20261120')],[official('20261120')],[result('20261120'),result('20261120')]).joinedCount,0);
const upset=run([record('20261120')],[official('20261120')],[{...result('20261120'),finishOrder:[6,1,2,3,4,5]}]);
assert.equal(upset.summary.winnerByScoreRank[6],1);
assert.equal(upset.summary.topScoreByActualFinish[2],1);
assert.equal(upset.summary.topScoreMisses.length,1);
assert.equal(upset.summary.topScoreMisses[0].scoreGapToWinner,5);
assert.equal(upset.eligibleForCalibration,false);
assert.deepEqual(upset.summary.featureAvailability.preRaceAverageSTAvailable,{available:0,total:6});
assert.deepEqual(upset.summary.featureAvailability.makulabo50Available,{available:0,total:6});
assert.equal(upset.summary.topScoreMisses[0].topScoreFeatures.preRaceAverageSTAvailable,false);
assert.equal(upset.summary.topScoreMisses[0].winnerFeatures.makulabo50Available,false);
const duplicate=run([record('20261120'),record('20261120')],[official('20261120')],[result('20261120')]);
assert.equal(duplicate.joinedCount,0);
assert.equal(duplicate.rows.filter(x=>x.status==='held_duplicate_saved_prediction').length,2);
const cancelled=date=>({...record(date),venue:9,race:6});
const cancelledOfficial=date=>({...official(date),venue:9,race:6});
const cancelledResult=date=>({...result(date),venue:9,race:6});
assert.equal(run([cancelled('20261120')],[cancelledOfficial('20261120')],[cancelledResult('20261120')]).rows.length,0);
assert.equal(run([cancelled('20261121')],[cancelledOfficial('20261121')],[cancelledResult('20261121')]).joinedCount,1);
console.log('Date-scoped retrospective join, duplicate safety and rank-distribution tests passed');
