import assert from 'node:assert/strict';
import {splitScoreLeaderTickets,compareScoreLeaderTickets} from './score-leader-favorite-upset.mjs';
const scores=[{boat:4,score:100},{boat:1,score:90},{boat:2,score:80},{boat:3,score:70},{boat:5,score:60},{boat:6,score:50}];
const p=splitScoreLeaderTickets(scores);
assert.equal(p.ready,true);
assert.equal(p.leaderBoat,4);
assert.equal(p.main.length,6);
assert.equal(p.upset.length,6);
assert(p.main.every(x=>x[0]===4));
assert(p.upset.every(x=>x[0]!==4));
assert.equal(p.upset.filter(x=>x.includes(4)).length,3);
assert.equal(p.upset.filter(x=>!x.includes(4)).length,3);
assert.equal(new Set([...p.main,...p.upset].map(x=>x.join('-'))).size,12);
assert.equal(p.scoreWeightsChanged,false);
const q=splitScoreLeaderTickets(scores.slice().reverse());
assert.deepEqual(p.main,q.main);
assert.deepEqual(p.upset,q.upset);
assert.equal(splitScoreLeaderTickets([...scores.slice(0,5),scores[0]]).ready,false);
assert.equal(splitScoreLeaderTickets(scores.map(x=>({...x,score:NaN}))).ready,false);
const matched=compareScoreLeaderTickets(p,p.main[0]);
assert.equal(matched.mainExact,true);
assert.equal(matched.upsetExact,false);
assert.equal(matched.eligibleForScoreChange,false);
assert.equal(compareScoreLeaderTickets(p,[1,1,2]).status,'not_comparable');
console.log('Score leader favorite/upset research tests passed');
