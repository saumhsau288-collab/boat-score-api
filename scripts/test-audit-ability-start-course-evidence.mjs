import assert from 'node:assert/strict';
import {auditAbilityStartCourseEvidence as audit} from './audit-ability-start-course-evidence.mjs';
const racers=Array.from({length:6},(_,i)=>({boat:i+1,racerId:String(4000+i),nationalWinRate:5,localWinRate:4,motorTwoWinRate:40,makulaboIdentityVerified:false,labelledFrameFinishSample:{runs:i===4?1:49,firstPlaceRate:0}}));
const ability={status:'descriptive_cross_source_comparison',racers};
const noStart=audit(ability,null);
assert.equal(noStart.status,'incomplete_evidence');
assert.equal(noStart.verifiedStartCount,0);
assert.equal(noStart.verifiedCourseCount,0);
assert.equal(noStart.racers[4].labelledFrameFinishSample.runs,1);
assert.deepEqual(noStart.racers[0].missing,['verified_pre_race_average_st','verified_entry_course','verified_makulabo_identity']);
const predicted={status:'verified',racers:racers.map(r=>({boat:r.boat,course:r.boat,averageST:0.15,startVerified:true}))};
const result=audit(ability,predicted);
assert.equal(result.verifiedStartCount,6);
assert.equal(result.verifiedCourseCount,0);
assert.equal(result.racers[0].entryCourse,null);
assert.equal(result.readyForHistoricalCalibration,false);
assert.equal(result.scoreChangeApplied,false);
assert.equal(audit(null,predicted).status,'held');
console.log('Ability/start/course evidence audit tests passed');
