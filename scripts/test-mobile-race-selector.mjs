// Static mobile selector regression: check inline JS syntax without browser dependencies.
import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const html=fs.readFileSync(new URL('../research/boat-score-2-race-selector.html',import.meta.url),'utf8');
const start=html.indexOf('<script>');const end=html.indexOf('</script>',start);const scripts=start>=0&&end>start?[html.slice(start+8,end)]:[];
assert.equal(scripts.length,1,'Expected one inline selector script');
new vm.Script(scripts[0],{filename:'boat-score-2-race-selector.inline.js'});
for(const selector of ['#date','#venue','#race','#prediction-view','#open-makulabo'])assert.ok(html.includes(selector),selector);
assert.ok(html.includes('data.status!==\'experimental\''),'Must reject unavailable predictions');
assert.ok(html.includes("data.date!==x.date.replaceAll('-','')"),'Must reject mismatched date');
assert.ok(html.includes('data.venue!==Number(x.venue)'),'Must reject mismatched venue');
assert.ok(html.includes('data.race!==Number(x.race)'),'Must reject mismatched race');
assert.ok(html.includes('requestVersion!==predictionRequestVersion'),'Stale API responses must be ignored');
assert.ok(html.includes('predictionRequestVersion++'),'Changing selection must invalidate in-flight prediction');
assert.ok(html.includes('new URL(location.origin)'),'Preview selector must call same-origin API');
assert.ok(!html.includes('id="preview-api"'),'No manual API URL entry required');
assert.ok(html.includes('id="morning"'),'Morning ranking status must be visible');
assert.ok(!html.includes('id="workflow"')&&!html.includes('id="prediction-file"')&&!html.includes('id="copy"'),'Unneeded workflow, file and copy controls must be removed');
assert.equal((html.match(/<button id="select"/g)??[]).length,1,'Only one primary prediction button');
assert.ok(html.includes('id="racer-table"'),'Six-racer comparison table must be present');
assert.ok(html.includes('data.indicators.hasRecent50Label')&&html.includes('data.indicators.hasRegistrationId'),'Makulabo source evidence must be visible to user');
assert.ok(html.includes('id="beforeinfo"')&&html.includes('/owpc/pc/race/beforeinfo'),'Official pre-race information link must match selection');
assert.ok(html.includes('beforeinfo.search=url.search'),'Official racelist and beforeinfo must use the same race parameters');
for(const column of ['全国勝率','当地勝率','まくらぼ50走勝率','モーター2連対率','平均ST','展示タイム','直前進入','評価点'])assert.ok(html.includes(column),'Missing comparison column '+column);
assert.ok(html.includes("sort((a,b)=>a.boat-b.boat)"),'Comparison table must use boat order');
assert.ok(html.includes("typeof value==='number'&&Number.isFinite(value)"),'Missing values must not become zero');
console.log('Mobile selector static regression passed');
