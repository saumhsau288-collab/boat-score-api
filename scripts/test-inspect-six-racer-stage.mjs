import assert from 'node:assert/strict';
import {inspectSixRacerStage} from './inspect-six-racer-stage.mjs';
const rows=Array.from({length:6},(_,i)=>({boat:i+1,racerId:String(4001+i),nationalWinRate:6,localWinRate:0,motorTwoWinRate:34,recent50WinRate:null,averageStartTiming:.15,exhibitionScore:null,exhibitionStartTiming:null,course:null}));
let r=inspectSixRacerStage(rows,'morning');
assert.equal(r.complete,false);
assert.equal(r.missing.recent50WinRate,6);
assert.equal(r.missing.exhibitionScore,undefined);
assert.equal(r.invalid.course,undefined);
r=inspectSixRacerStage(rows,'pre_cutoff');
assert.equal(r.missing.exhibitionScore,6);
assert.equal(r.missing.exhibitionStartTiming,6);
assert.equal(r.invalid.course,6);
const full=rows.map(x=>({...x,recent50WinRate:44,exhibitionScore:55,exhibitionStartTiming:.12,course:x.boat}));
assert.equal(inspectSixRacerStage(full,'morning').complete,true);
assert.equal(inspectSixRacerStage(full,'pre_cutoff').complete,true);
assert.equal(inspectSixRacerStage(full,'pre_cutoff').authenticated,false);
const duplicate=full.map(x=>({...x}));duplicate[1].racerId=duplicate[0].racerId;
assert.equal(inspectSixRacerStage(duplicate,'morning').invalid.racerId,1);
const bad=full.map(x=>({...x}));bad[0].nationalWinRate=NaN;
assert.equal(inspectSixRacerStage(bad,'morning').invalid.nationalWinRate,1);
assert.throws(()=>inspectSixRacerStage(full,'other'));
console.log('PASS: stage-aware original input completeness (synthetic only)');
