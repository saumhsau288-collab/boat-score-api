import assert from 'node:assert/strict';
import {officialResultUrl,captureOfficialResultEvidence} from './capture-official-result-evidence.mjs';
const selection={date:'20261120',venue:'18',race:1};
const target=officialResultUrl(selection);
assert.equal(target.status,'ok');
assert.equal(new URL(target.url).pathname,'/owpc/pc/race/raceresult');
assert.equal(officialResultUrl({...selection,race:13}).status,'invalid_selection');
const response=(url,html='<html>official result</html>')=>({url,ok:true,status:200,headers:{get:()=> 'text/html; charset=utf-8'},text:async()=>html});
const now=()=> '2026-11-20T11:00:00.000Z';
const good=await captureOfficialResultEvidence(selection,async()=>response(target.url),now,true);
assert.equal(good.status,'official_result_source_captured');
assert.equal(good.verified,false);
assert.equal(good.eligibleForCalibration,false);
assert.equal(good.finishByBoat,null);
assert.equal(good.responseSha256.length,64);
assert.ok(good.rawHtml.includes('official result'));
const wrong=await captureOfficialResultEvidence(selection,async()=>response(target.url.replace('jcd=18','jcd=17')),now);
assert.equal(wrong.status,'official_result_source_rejected');
assert.equal(wrong.eligibleForCalibration,false);
const missing=await captureOfficialResultEvidence(selection,async()=>({...response(target.url),url:undefined}),now);
assert.equal(missing.status,'official_result_source_rejected');
console.log('Official result evidence capture tests passed');
