import assert from 'node:assert/strict';
import {fetchWithTimeoutRetry} from './fetch-with-timeout-retry.mjs';
const success=async()=>({status:200,text:async()=>'{"ready":true}'});
const timeout=async()=>{throw new Error('The operation was aborted due to timeout');};
const unavailable=async()=>({status:503,text:async()=>'{"error":true}'});
let calls=0;
let result=await fetchWithTimeoutRetry('https://example.com',{fetchFn:async()=>{calls++;return success();}});
assert.equal(calls,1);assert.equal(result.attempts.length,1);assert.equal(result.response.status,200);
calls=0;
result=await fetchWithTimeoutRetry('https://example.com',{fetchFn:async()=>{calls++;return calls===1?timeout():success();}});
assert.equal(calls,2);assert.equal(result.attempts.length,2);assert.equal(result.attempts[0].error.includes('timeout'),true);assert.equal(result.response.status,200);
calls=0;
result=await fetchWithTimeoutRetry('https://example.com',{fetchFn:async()=>{calls++;return timeout();}});
assert.equal(calls,2);assert.equal(result.attempts.length,2);assert.equal(typeof result.error,'string');
calls=0;
result=await fetchWithTimeoutRetry('https://example.com',{fetchFn:async()=>{calls++;throw new Error('connection reset');}});
assert.equal(calls,1);assert.equal(result.attempts.length,1);
calls=0;
result=await fetchWithTimeoutRetry('https://example.com',{fetchFn:async()=>{calls++;return unavailable();}});
assert.equal(calls,1);assert.equal(result.response.status,503);
console.log('Bounded timeout retry tests passed');
