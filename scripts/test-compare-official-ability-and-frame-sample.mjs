import assert from 'node:assert/strict';
import {compareOfficialAbilityAndFrameSample as compare} from './compare-official-ability-and-frame-sample.mjs';
import {describeMakulaboFinishSample} from './describe-makulabo-finish-sample.mjs';
import {summarizeMakulaboFinishComparison} from './summarize-makulabo-finish-comparison.mjs';
const counts=[[22,12,9,5,2,0],[8,15,7,8,5,6],[11,7,11,7,9,4],[6,4,15,9,6,9],[0,0,0,0,1,0],[1,2,8,8,12,18]];
const sample=summarizeMakulaboFinishComparison(describeMakulaboFinishSample({verified:true,parsedRows:counts.map((counts,i)=>({boat:i+1,name:'R'+i,counts,runs:counts.reduce((a,b)=>a+b,0)}))}));
const snapshot={status:'captured_research_inputs',source:'verified_official_metrics',racers:counts.map((_,i)=>({boat:i+1,racerId:String(4000+i),name:'R'+i,sourceVerified:true,nationalWinRate:5,localWinRate:i===4?0:4,motorTwoWinRate:40}))};
const result=compare(snapshot,sample);
assert.equal(result.status,'descriptive_cross_source_comparison');
assert.equal(result.racers[0].labelledFrameFinishSample.firstPlaceRate,44);
assert.equal(result.racers[0].labelledFrameFinishSample.top2Rate,68);
assert.equal(result.racers[0].labelledFrameFinishSample.top3Rate,86);
assert.equal(result.racers[4].labelledFrameFinishSample.runs,1);
assert.equal(result.racers[4].localWinRate,5);
assert.equal(result.racers[4].localRateFallbackApplied,true);
assert.equal(result.racers[4].averageSTVerified,false);
assert.equal(result.racers[4].entryCourseVerified,false);
assert.equal(result.makulaboIdentityVerified,false);
assert.equal(result.scoreChangeApplied,false);
assert.equal(result.eligibleForCalibration,false);
assert.equal(compare({...snapshot,racers:snapshot.racers.map(r=>({...r,sourceVerified:false}))},sample).status,'held');
console.log('Research official ability and frame sample separation tests passed');
