import assert from 'node:assert/strict';
import {linkResearchSnapshots} from './link-research-feature-snapshots.mjs';
const capture={records:[{date:'20261120',venue:2,race:1,receivedAt:'2026-11-20T00:30:00Z',responseSha256:'a'.repeat(64),response:{ready:true}}]};
const noSnapshot=linkResearchSnapshots(capture);
assert.equal(noSnapshot.total,1);
assert.equal(noSnapshot.linked,0);
assert.equal(noSnapshot.calibrationEligible,0);
assert(noSnapshot.rows[0].errors.includes('feature_snapshot_missing'));
const fields=['nationalWinRate','localWinRate','motorTwoWinRate','recent50WinRate','exhibitionScore','startTiming'];
const sources=Object.fromEntries(fields.map(f=>[f,'https://example.org/'+f]));
const racers=Array.from({length:6},(_,i)=>({boat:i+1,racerId:String(4000+i),entryCourse:i+1,nationalWinRate:6,localWinRate:0,motorTwoWinRate:40,recent50WinRate:50,exhibitionScore:50,startTiming:0.15,sources}));
const snapshot={date:'20261120',venue:2,race:1,capturedAt:'2026-11-20T00:00:00Z',officialCutoffAt:'2026-11-20T01:00:00Z',officialCutoffSourceUrl:'https://www.boatrace.jp/owpc/pc/race/racelist',racers};
const linked=linkResearchSnapshots(capture,[snapshot]);
assert.equal(linked.linked,1);
assert.equal(linked.completeFeatureSnapshots,1);
assert.equal(linked.calibrationEligible,0);
assert.equal(linkResearchSnapshots(capture,[{...snapshot,capturedAt:'2026-11-20T00:40:00Z'}]).rows[0].errors.includes('snapshot_not_captured_before_prediction_response'),true);
assert.throws(()=>linkResearchSnapshots(capture,[snapshot,snapshot]),/duplicate_snapshot/);
console.log('research prediction-feature linkage tests passed');
