import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const source=readFileSync(new URL('./worker.js',import.meta.url),'utf8');
const start=source.indexOf('function classifyDailyRaceCandidates(races) {');
const end=source.indexOf('\nfunction summarizeHistoricalOuterFollow(',start);
assert(start>=0&&end>start,'candidate ranking function exists');
const classify=vm.runInNewContext('('+source.slice(start,end)+')');
const scores=[{boat:1,score:20},{boat:2,score:15},{boat:3,score:12},{boat:4,score:10},{boat:5,score:8},{boat:6,score:5}];
const eligible={date:'20261122',venue:21,race:3,officialVerified:true,statsVerified:true,rankedScores:scores};
const main=classify([eligible]).main[0];
assert(main,'eligible race ranked');
assert.deepEqual(Array.from(main.predictedOrder),[1,2,3,4,5,6]);
assert.equal(main.score,5);
const invalid=classify([{...eligible,rankedScores:scores.slice(0,5)}]);
assert.equal(invalid.main.length+invalid.upset.length+invalid.chaos.length,0);
assert.equal(invalid.held,1);
const formatStart=source.indexOf('function formatVenueRanking(data){');
const formatEnd=source.indexOf('\nasync function show(',formatStart);
assert(formatStart>=0&&formatEnd>formatStart,'ranking formatter exists');
const format=vm.runInNewContext('('+source.slice(formatStart,formatEnd)+')');
const formatted=format({date:'20261122',venue:21,scanned:12,eligible:1,held:11,categories:{main:[main],upset:[],chaos:[]}});
assert(formatted.includes('暫定スコア 5.00 / 予想順位 1-2-3-4-5-6'));
const missing=format({date:'20261122',venue:21,categories:{main:[{race:3,score:5}],upset:[],chaos:[]}});
assert(missing.includes('予想順位 未確認'));
console.log('Six-boat predicted order is rendered from existing scores, with missing data held.');
